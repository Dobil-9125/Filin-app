const SYSTEM = `${RULES}<knowledge>\n${KNOWLEDGE}\n</knowledge>`;

type Turn = { role: "user" | "assistant"; content: string };
type Pet = { name?: string; species?: string; age?: string | number; weight?: string | number; breed?: string; avoid?: string[]; conditions?: string };

const clip = (v: unknown, n: number) => String(v ?? "").slice(0, n).trim();

function petLine(p: Pet | undefined): string {
  if (!p || typeof p !== "object") return "";
  const parts = [
    p.name && `이름 ${clip(p.name, 20)}`,
    p.species && clip(p.species, 10),
    p.age !== undefined && p.age !== "" && `${clip(p.age, 10)}살`,
    p.weight !== undefined && p.weight !== "" && `${clip(p.weight, 10)}kg`,
    p.breed && clip(p.breed, 30),
    Array.isArray(p.avoid) && p.avoid.length > 0 && `피해야 할 재료: ${p.avoid.slice(0, 10).map((a) => clip(a, 20)).join(", ")}`,
    p.conditions && `지병·약: ${clip(p.conditions, 100)}`,
  ].filter(Boolean);
  return parts.length ? `[아이 정보] ${parts.join(" · ")}` : "";
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  if (req.method !== "POST") return json({ error: "method" }, 405);

  // 로그인한 회원만 쓸 수 있어요 (API 비용 보호)
  const token = (req.headers.get("Authorization") ?? "").replace(/^Bearer\s+/i, "");
  const key = req.headers.get("apikey") ?? Deno.env.get("SUPABASE_ANON_KEY") ?? "";
  const sb = createClient(Deno.env.get("SUPABASE_URL") ?? "", key);
  const { data, error } = await sb.auth.getUser(token);
  if (error || !data?.user) return json({ error: "login" }, 401);

  let body: { messages?: Turn[]; pet?: Pet };
  try { body = await req.json(); } catch { return json({ error: "bad_json" }, 400); }

  const turns = (Array.isArray(body.messages) ? body.messages : [])
    .filter((m) => m && (m.role === "user" || m.role === "assistant") && typeof m.content === "string" && m.content.trim())
    .slice(-MAX_TURNS)
    .map((m) => ({ role: m.role, content: clip(m.content, MAX_CHARS) }));
  while (turns.length && turns[0].role !== "user") turns.shift();
  if (!turns.length || turns[turns.length - 1].role !== "user") return json({ error: "no_question" }, 400);

  const pet = petLine(body.pet);
  const messages: Anthropic.MessageParam[] = turns.map((t, i) =>
    i === turns.length - 1 && pet ? { role: "user", content: `${pet}\n\n${t.content}` } : t
  );

  try {
    const res = await anthropic.messages.create({
      model: MODEL,
      max_tokens: 2000,
      output_config: { effort: "low" },
      system: [{ type: "text", text: SYSTEM, cache_control: { type: "ephemeral" } }],
      messages,
    });
    if (res.stop_reason === "refusal") {
      return json({ answer: "이 질문에는 답하기 어려워요. 걱정되면 FILIN 수의사 상담이나 가까운 동물병원에 물어봐 주세요." });
    }
    const answer = res.content.flatMap((b) => (b.type === "text" ? [b.text] : [])).join("").trim();
    return json({ answer: answer || "답을 만들지 못했어요. 다시 한 번 물어봐 주세요." });
  } catch (e) {
    if (e instanceof Anthropic.RateLimitError) return json({ error: "busy" }, 429);
    if (e instanceof Anthropic.AuthenticationError) return json({ error: "server_key" }, 500);
    if (e instanceof Anthropic.APIError) return json({ error: "api", status: e.status }, 502);
    return json({ error: "server" }, 500);
  }
});
